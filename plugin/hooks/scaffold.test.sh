#!/usr/bin/env bash
#
# scaffold.test.sh — deterministic, offline tests for scaffold.sh's
# sweap-managed file sync: the provenance stamp, cmp-based drift rewrite, the
# compact/clear skip, file modes, the no-jq path, and the gitignore self-heal.
#
# Run:  bash plugin/hooks/scaffold.test.sh
# Exit: 0 = all pass, 1 = a failure (prints which case).
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCAFFOLD="$HERE/scaffold.sh"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/scaffold-test.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
pass=0; fail=0
want() { # want <desc> <expected> <actual>
  if [ "$2" = "$3" ]; then pass=$((pass+1)); printf '  PASS  %s\n' "$1"
  else fail=$((fail+1)); printf '  FAIL  %s (got [%s], wanted [%s])\n' "$1" "$3" "$2"; fi
}
ok() { # ok <desc> <command...> ; passes when the command exits 0
  local desc="$1"; shift
  if "$@"; then pass=$((pass+1)); printf '  PASS  %s\n' "$desc"
  else fail=$((fail+1)); printf '  FAIL  %s\n' "$desc"; fi
}
hash_of() { # mirrors scaffold.sh
  local h=""
  if command -v sha256sum >/dev/null 2>&1; then h="$(sha256sum "$1" | awk '{print $1}')"
  elif command -v shasum >/dev/null 2>&1; then h="$(shasum -a 256 "$1" | awk '{print $1}')"; fi
  if [ -n "$h" ]; then printf '%s' "$h" | cut -c1-12; else printf 'unknown'; fi
}
RE='^# Code generated by sweap 9\.9\.9 \(source sha256:[0-9a-f]{12}\)\. DO NOT EDIT\.$'
if [ "$(uname)" = "Darwin" ]; then mode_of() { stat -f %Lp "$1"; }; else mode_of() { stat -c %a "$1"; }; fi

mk_fixture() { # mk_fixture <dir> ; creates <dir>/proj and <dir>/plugin
  local d="$1"
  rm -rf "$d"; mkdir -p "$d/proj/.github/workflows" "$d/plugin/templates/.github/workflows" "$d/plugin/hooks"
  git -C "$d/proj" init -q
  printf '# Project\n\n## sweap config\n```\nverify.e2e: true\n```\n' > "$d/proj/CLAUDE.md"
  mkdir -p "$d/plugin/.claude-plugin"; printf '{"version":"9.9.9"}\n' > "$d/plugin/.claude-plugin/plugin.json"
  printf 'name: audit-gate\non: [pull_request]\njobs: {}\n' > "$d/plugin/templates/.github/workflows/audit-gate.yml"
  printf 'name: Claude Review\non: [pull_request]\njobs: {}\n' > "$d/plugin/templates/.github/workflows/claude-review.yml"
  for s in audit-gate roadmap-lint ci-lane; do
    printf '#!/usr/bin/env bash\necho %s\n' "$s" > "$d/plugin/hooks/$s.sh"
  done
}
run_scaffold() { # run_scaffold <fixture-dir> [json-payload]
  CLAUDE_PROJECT_DIR="$1/proj" CLAUDE_PLUGIN_ROOT="$1/plugin" bash "$SCAFFOLD" <<< "${2:-}" 2>/dev/null
}
snapshot() { # snapshot <fixture-dir> <snap-dir>
  rm -rf "$2"; mkdir -p "$2"
  for f in .github/workflows/audit-gate.yml .github/scripts/audit-gate.sh .github/scripts/roadmap-lint.sh .github/scripts/ci-lane.sh; do
    mkdir -p "$2/$(dirname "$f")"; cp "$1/proj/$f" "$2/$f"
  done
}
same_as_snapshot() { # same_as_snapshot <fixture-dir> <snap-dir>
  for f in .github/workflows/audit-gate.yml .github/scripts/audit-gate.sh .github/scripts/roadmap-lint.sh .github/scripts/ci-lane.sh; do
    cmp -s "$1/proj/$f" "$2/$f" || return 1
  done
}

echo "scaffold.test.sh:"
F="$WORK/f1"; mk_fixture "$F"; P="$F/proj"

# --- a. startup, fresh --------------------------------------------------------
out="$(run_scaffold "$F" '{"source":"startup"}')"
for f in .github/workflows/audit-gate.yml .github/scripts/audit-gate.sh .github/scripts/roadmap-lint.sh .github/scripts/ci-lane.sh; do
  ok "a: $f exists" test -f "$P/$f"
done
want "a: script line 1 is the shebang" '#!/usr/bin/env bash' "$(sed -n 1p "$P/.github/scripts/audit-gate.sh")"
ok   "a: script line 2 matches the stamp regex" grep -qE "$RE" <(sed -n 2p "$P/.github/scripts/audit-gate.sh")
ok   "a: script stamp carries the SOURCE hash" grep -qF "sha256:$(hash_of "$F/plugin/hooks/audit-gate.sh")" <(sed -n 2p "$P/.github/scripts/audit-gate.sh")
ok   "a: script is executable" test -x "$P/.github/scripts/audit-gate.sh"
want "a: script body follows the banner" "$(tail -n +2 "$F/plugin/hooks/ci-lane.sh")" "$(tail -n +5 "$P/.github/scripts/ci-lane.sh")"
ok   "a: yml line 1 matches the stamp regex" grep -qE "$RE" <(sed -n 1p "$P/.github/workflows/audit-gate.yml")
want "a: yml line 4 is name: audit-gate" 'name: audit-gate' "$(sed -n 4p "$P/.github/workflows/audit-gate.yml")"
ok   "a: yml is NOT executable" test ! -x "$P/.github/workflows/audit-gate.yml"
ok   "a: stdout announces installed/updated" grep -q 'installed/updated' <<< "$out"
snapshot "$F" "$WORK/snap_a"

# --- b. startup again: unchanged, silent --------------------------------------
out="$(run_scaffold "$F" '{"source":"startup"}')"
ok   "b: all 4 unchanged on a second startup" same_as_snapshot "$F" "$WORK/snap_a"
want "b: stdout empty" "" "$out"

# --- c. plugin source drifts -> dest rewritten, only that file named ----------
echo 'echo more' >> "$F/plugin/hooks/audit-gate.sh"
out="$(run_scaffold "$F" '{"source":"startup"}')"
ok   "c: drifted dest rewritten" test "$(sed -n 2p "$P/.github/scripts/audit-gate.sh")" != "$(sed -n 2p "$WORK/snap_a/.github/scripts/audit-gate.sh")"
ok   "c: new stamp carries the new source hash" grep -qF "sha256:$(hash_of "$F/plugin/hooks/audit-gate.sh")" <(sed -n 2p "$P/.github/scripts/audit-gate.sh")
ok   "c: stdout names audit-gate.sh" grep -q '\.github/scripts/audit-gate\.sh' <<< "$out"
# heal_msg's standing advice mentions ci-lane.sh by name; only the healed LIST
# (the text before ". These are sweap-managed") says what was rewritten.
healed_list="$(sed -E 's/\. These are sweap-managed.*//' <<< "$out")"
ok   "c: healed list does not name the other three" test "$(grep -c 'roadmap-lint\.sh\|ci-lane\.sh\|audit-gate\.yml' <<< "$healed_list")" -eq 0
snapshot "$F" "$WORK/snap_c"

# --- d. local edit to a dest -> overwritten ----------------------------------
echo 'tampered' >> "$P/.github/scripts/ci-lane.sh"
out="$(run_scaffold "$F" '{"source":"startup"}')"
ok   "d: local edit overwritten (cmp to fresh stamped copy)" cmp -s "$P/.github/scripts/ci-lane.sh" "$WORK/snap_c/.github/scripts/ci-lane.sh"
ok   "d: stdout names ci-lane.sh" grep -q 'installed/updated.*ci-lane\.sh' <<< "$out"

# --- e. drift + compact/clear -> skipped -------------------------------------
echo 'echo drift' >> "$F/plugin/hooks/roadmap-lint.sh"
out="$(run_scaffold "$F" '{"source":"compact"}')"
ok   "e: compact does not rewrite" cmp -s "$P/.github/scripts/roadmap-lint.sh" "$WORK/snap_c/.github/scripts/roadmap-lint.sh"
want "e: compact stdout empty" "" "$out"
out="$(run_scaffold "$F" '{"source":"clear"}')"
ok   "e: clear does not rewrite" cmp -s "$P/.github/scripts/roadmap-lint.sh" "$WORK/snap_c/.github/scripts/roadmap-lint.sh"
want "e: clear stdout empty" "" "$out"

# --- f. every other source syncs ---------------------------------------------
redrift() { echo "echo drift-$1" >> "$F/plugin/hooks/roadmap-lint.sh"; }
for s in resume fork init-command; do
  run_scaffold "$F" "{\"source\":\"$s\"}" >/dev/null
  ok "f: source=$s rewrites" grep -qF "sha256:$(hash_of "$F/plugin/hooks/roadmap-lint.sh")" <(sed -n 2p "$P/.github/scripts/roadmap-lint.sh")
  redrift "$s"
done
run_scaffold "$F" "{\"cwd\":\"$P\"}" >/dev/null
ok "f: payload without source rewrites" grep -qF "sha256:$(hash_of "$F/plugin/hooks/roadmap-lint.sh")" <(sed -n 2p "$P/.github/scripts/roadmap-lint.sh")

# --- g. no-jq path ------------------------------------------------------------
mkdir -p "$WORK/bin"
for f in /usr/bin/* /bin/* /sbin/sha256sum; do [ -x "$f" ] && ln -s "$f" "$WORK/bin/" 2>/dev/null; done
rm -f "$WORK/bin/jq"
if PATH="$WORK/bin" command -v jq >/dev/null 2>&1; then
  echo "  SKIP  g: could not build a PATH without jq"
else
  G="$WORK/g"; mk_fixture "$G"; GP="$G/proj"
  out="$(PATH="$WORK/bin" run_scaffold "$G" '{"source":"startup"}')"
  ok   "g(no-jq): script line 2 matches the stamp regex" grep -qE "$RE" <(sed -n 2p "$GP/.github/scripts/audit-gate.sh")
  ok   "g(no-jq): yml line 1 matches the stamp regex" grep -qE "$RE" <(sed -n 1p "$GP/.github/workflows/audit-gate.yml")
  ok   "g(no-jq): plain-text stdout announces installed/updated" grep -q 'installed/updated' <<< "$out"
  ok   "g(no-jq): stdout is not JSON" test "${out:0:1}" != "{"
  snapshot "$G" "$WORK/snap_g"
  echo 'echo drift' >> "$G/plugin/hooks/roadmap-lint.sh"
  out="$(PATH="$WORK/bin" run_scaffold "$G" '{"source":"compact"}')"
  ok   "g(no-jq): compact with drift does not rewrite" same_as_snapshot "$G" "$WORK/snap_g"
  want "g(no-jq): compact stdout empty" "" "$out"
fi

# --- h. gitignore self-heal still runs on compact -----------------------------
grep -vF '.claude/sweap-run.md' "$P/.gitignore" > "$P/.gitignore.tmp" && mv "$P/.gitignore.tmp" "$P/.gitignore"
run_scaffold "$F" '{"source":"compact"}' >/dev/null
ok "h: gitignore self-heal runs on compact" grep -qF '.claude/sweap-run.md' "$P/.gitignore"

# --- i. stamp stability -------------------------------------------------------
I="$WORK/i"; mk_fixture "$I"
run_scaffold "$I" '{"source":"startup"}' >/dev/null; snapshot "$I" "$WORK/snap_i1"
run_scaffold "$I" '{"source":"startup"}' >/dev/null
ok "i: two startups are byte-identical" same_as_snapshot "$I" "$WORK/snap_i1"
ok "i: identical to fixture (a)'s copies" same_as_snapshot "$I" "$WORK/snap_a"

# --- j. fresh-file modes ------------------------------------------------------
want "j: fresh yml mode 644" 644 "$(mode_of "$I/proj/.github/workflows/audit-gate.yml")"
for s in audit-gate roadmap-lint ci-lane; do
  want "j: fresh $s.sh mode 755" 755 "$(mode_of "$I/proj/.github/scripts/$s.sh")"
done

# --- k. fresh repo: scripts land with the workflow (full-scaffold path) -------
K="$WORK/k"; mkdir -p "$K/proj"; git -C "$K/proj" init -q
CLAUDE_PLUGIN_ROOT="$(cd "$HERE/.." && pwd)"
out="$(CLAUDE_PROJECT_DIR="$K/proj" CLAUDE_PLUGIN_ROOT="$CLAUDE_PLUGIN_ROOT" bash "$SCAFFOLD" <<< '{"source":"startup"}' 2>/dev/null)"
for f in .github/workflows/audit-gate.yml .github/scripts/audit-gate.sh .github/scripts/roadmap-lint.sh .github/scripts/ci-lane.sh; do
  ok "k: fresh repo gets $f in the same session" test -f "$K/proj/$f"
done
ok "k: fresh yml is stamped" grep -qE '^# Code generated by sweap [^ ]+ \(source sha256:([0-9a-f]{12}|unknown)\)\. DO NOT EDIT\.$' <(sed -n 1p "$K/proj/.github/workflows/audit-gate.yml")
ok "k: vendored script matches the real plugin copy" test "$(tail -n +2 "$CLAUDE_PLUGIN_ROOT/hooks/ci-lane.sh")" = "$(tail -n +5 "$K/proj/.github/scripts/ci-lane.sh")"
ok "k: summary lists the vendored scripts" grep -q 'Installed sweap-managed CI controls.*audit-gate\.sh' <<< "$out"
out="$(CLAUDE_PROJECT_DIR="$K/proj" CLAUDE_PLUGIN_ROOT="$CLAUDE_PLUGIN_ROOT" bash "$SCAFFOLD" <<< '{"source":"startup"}' 2>/dev/null)"
want "k: second run is silent" "" "$out"

# --- k2. the playbook: adopt-if-present, and stamped as MARKDOWN --------------
# Only a repo that already vendors a copy gets one kept in lockstep; sweap does
# not impose a 1,500-line doc on consumers that never asked for it.
K2="$WORK/k2"; mkdir -p "$K2/proj"; git -C "$K2/proj" init -q
out="$(CLAUDE_PROJECT_DIR="$K2/proj" CLAUDE_PLUGIN_ROOT="$CLAUDE_PLUGIN_ROOT" bash "$SCAFFOLD" <<< '{"source":"startup"}' 2>/dev/null)"
ok "k2: a repo that does not vendor the playbook is not given one" \
  test ! -f "$K2/proj/docs/agentic-loop-playbook.md"

# Now opt in the way consumer A did — a copy already on disk — and re-run.
mkdir -p "$K2/proj/docs"; printf 'stale local copy\n' > "$K2/proj/docs/agentic-loop-playbook.md"
out="$(CLAUDE_PROJECT_DIR="$K2/proj" CLAUDE_PLUGIN_ROOT="$CLAUDE_PLUGIN_ROOT" bash "$SCAFFOLD" <<< '{"source":"startup"}' 2>/dev/null)"
ok "k2: an existing vendored playbook is brought into lockstep" \
  test "$(wc -l < "$K2/proj/docs/agentic-loop-playbook.md")" -gt 100
ok "k2: markdown is stamped in an HTML COMMENT, not a stray H1" \
  grep -qE '^<!-- Code generated by sweap [^ ]+ \(source sha256:([0-9a-f]{12}|unknown)\)\. DO NOT EDIT\. -->$' \
  <(sed -n 1p "$K2/proj/docs/agentic-loop-playbook.md")
ok "k2: the rendered document still opens on its own H1" \
  grep -qE '^# ' <(sed -n 4p "$K2/proj/docs/agentic-loop-playbook.md")
ok "k2: body matches the real plugin copy byte for byte" \
  test "$(cat "$CLAUDE_PLUGIN_ROOT/playbook/agentic-loop-playbook.md")" = "$(tail -n +4 "$K2/proj/docs/agentic-loop-playbook.md")"
out="$(CLAUDE_PROJECT_DIR="$K2/proj" CLAUDE_PLUGIN_ROOT="$CLAUDE_PLUGIN_ROOT" bash "$SCAFFOLD" <<< '{"source":"startup"}' 2>/dev/null)"
want "k2: an in-lockstep playbook re-syncs silently" "" "$out"

# --- l. gitignore append is announced on the fast-guard path, once ------------
L="$WORK/fl"; mk_fixture "$L"
run_scaffold "$L" '{"source":"startup"}' >/dev/null           # first run: full scaffold + all rules
sed -i.bak '/sweap-run.md/d' "$L/proj/.gitignore"; rm -f "$L/proj/.gitignore.bak"   # a consumer scaffolded before the rule existed
out="$(run_scaffold "$L" '{"source":"startup"}')"
ok "l: heal path announces the appended ignore rule" grep -q 'appended sweap runtime ignore rules' <<<"$out"
ok "l: heal path names the rule" grep -q 'sweap-run.md' <<<"$out"
ok "l: rule is back" grep -qF '.claude/sweap-run.md' "$L/proj/.gitignore"
want "l: it is a single JSON emit" "1" "$(printf '%s\n' "$out" | grep -c hookSpecificOutput)"
out="$(run_scaffold "$L" '{"source":"startup"}')"
want "l: steady state is silent again" "" "$out"

# --- m. sweap-merge/ state dir is ignored: fresh scaffold + heal path ---------
ok "m: fresh scaffold ignores .claude/sweap-merge/" grep -qF '.claude/sweap-merge/' "$P/.gitignore"
M="$WORK/fm"; mk_fixture "$M"
run_scaffold "$M" '{"source":"startup"}' >/dev/null
sed -i.bak '/sweap-merge/d' "$M/proj/.gitignore"; rm -f "$M/proj/.gitignore.bak"   # a consumer scaffolded before 0.13.0
ok "m: rule removed for the test" test "$(grep -cF '.claude/sweap-merge/' "$M/proj/.gitignore")" -eq 0
out="$(run_scaffold "$M" '{"source":"startup"}')"
ok "m: heal path restores .claude/sweap-merge/" grep -qF '.claude/sweap-merge/' "$M/proj/.gitignore"
ok "m: heal message names the rule" grep -q 'appended sweap runtime ignore rules.*sweap-merge/' <<<"$out"
want "m: rule appears exactly once" "1" "$(grep -cF '.claude/sweap-merge/' "$M/proj/.gitignore")"

# --- s. .claude/settings.json self-heal: the bg-shell pressure reaper ---------
# The heal WRITES only when the target is an ordinary, writable, readable, LF,
# parseable JSON object that has not moved under it; every other case must
# announce its true cause and change nothing. mk_fixture's CLAUDE.md already has
# '## sweap config', so these run on the fast-guard path too — i.e. they also
# prove the heal reaches a repo scaffolded long before this rule existed.
KEY='CLAUDE_CODE_DISABLE_BG_SHELL_PRESSURE_REAP'
REAL_JQ="$(command -v jq)"
settings_of() { printf '%s/proj/.claude/settings.json' "$1"; }
is_json() { jq -e . "$1" >/dev/null 2>&1; }
# `command -v` consults bash's hash table, which by now holds jq's real path, so
# ask a fresh shell whether the jq-less PATH really is jq-less.
no_jq_path_works() { ! PATH="$WORK/bin" bash -c 'command -v jq' >/dev/null 2>&1; }
# Leading whitespace of the first indented line, rendered visibly: "4sp", "tab", "none".
first_indent() { awk '/^\t/ { print "tab"; exit } /^ / { match($0, / +/); print RLENGTH "sp"; exit } END { print "none" }' "$1" | head -1; }
diff_lines() { diff "$1" "$2" | grep -c '^[<>]'; }
seed_settings() { mkdir -p "$(dirname "$(settings_of "$1")")"; cat > "$(settings_of "$1")"; }
AM_ROOT=0; [ "$(id -u)" = "0" ] && AM_ROOT=1

# s1. absent -> created, containing just the env block
S1="$WORK/s1"; mk_fixture "$S1"
ok "s1: fixture starts with no settings.json" test ! -e "$(settings_of "$S1")"
out="$(run_scaffold "$S1" '{"source":"startup"}')"
ok   "s1: settings.json created" test -f "$(settings_of "$S1")"
ok   "s1: it is valid JSON" is_json "$(settings_of "$S1")"
want "s1: the key is set to 1" '1' "$(jq -r --arg k "$KEY" '.env[$k]' "$(settings_of "$S1")")"
want "s1: nothing else was invented" 'env' "$(jq -r 'keys | join(",")' "$(settings_of "$S1")")"
want "s1: a file we CREATE gets mode 644" 644 "$(mode_of "$(settings_of "$S1")")"
ok   "s1: announced by key name" grep -q "env\.$KEY" <<<"$out"
# Discriminating: the gitignore heal's message also contains "commit it", so
# assert on a phrase only the settings message can produce.
ok   "s1: announcement asks for review + commit (settings wording, not gitignore's)" \
  grep -q 'This is a working-tree edit in the main checkout: review it and COMMIT it' <<<"$out"
ok   "s1: it does not claim to protect the current session" \
  grep -q 'applies only to sessions started after it lands — it does nothing for this session' <<<"$out"
ok   "s1: it does not leak sweap-internal repo knowledge" \
  test "$(grep -c 'both consumer repos track' <<<"$out")" -eq 0

# s2. present without the key, with other top-level keys and an unrelated env entry
S2="$WORK/s2"; mk_fixture "$S2"
seed_settings "$S2" <<'JSON'
{
  "enabledPlugins": { "sweap@sweap": true },
  "permissions": { "allow": ["Bash(just test:*)"] },
  "env": { "SOME_OTHER_VAR": "keep-me" }
}
JSON
out="$(run_scaffold "$S2" '{"source":"startup"}')"
ok   "s2: still valid JSON" is_json "$(settings_of "$S2")"
want "s2: key added" '1' "$(jq -r --arg k "$KEY" '.env[$k]' "$(settings_of "$S2")")"
want "s2: enabledPlugins survived" 'true' "$(jq -r '.enabledPlugins["sweap@sweap"]' "$(settings_of "$S2")")"
want "s2: permissions survived" 'Bash(just test:*)' "$(jq -r '.permissions.allow[0]' "$(settings_of "$S2")")"
want "s2: the unrelated env entry survived" 'keep-me' "$(jq -r '.env.SOME_OTHER_VAR' "$(settings_of "$S2")")"
want "s2: no top-level key was dropped" 'enabledPlugins,env,permissions' "$(jq -r 'keys | join(",")' "$(settings_of "$S2")")"
ok   "s2: announced as adding a KEY, not a file" grep -q "added the key env\.$KEY" <<<"$out"

# s3. the key already has a value -> never overwritten, even when it is "0"
S3="$WORK/s3"; mk_fixture "$S3"
seed_settings "$S3" <<JSON
{"env":{"$KEY":"0"},"model":"opus"}
JSON
cp "$(settings_of "$S3")" "$WORK/s3.before"
out="$(run_scaffold "$S3" '{"source":"startup"}')"
ok   "s3: an explicit 0 is left byte-identical" cmp -s "$(settings_of "$S3")" "$WORK/s3.before"
ok   "s3: and nothing is announced about settings" test "$(grep -c "$KEY" <<<"$out")" -eq 0

# s4. the four "cannot parse / wrong shape" causes must be told apart -----------
# The first cut said "could not be parsed as JSON" for all of them; three are
# valid JSON, so that message sent people to fix the wrong thing.
check_bail() { # check_bail <tag> <fixture> <content> <phrase that must appear>
  local tag="$1" d="$WORK/$2" content="$3" phrase="$4" o
  mk_fixture "$d"; printf '%s' "$content" | seed_settings "$d"
  cp "$(settings_of "$d")" "$WORK/$2.before"
  o="$(run_scaffold "$d" '{"source":"startup"}')"
  ok "$tag: file left byte-identical" cmp -s "$(settings_of "$d")" "$WORK/$2.before"
  ok "$tag: the announcement names the true cause" grep -q "$phrase" <<<"$o"
  ok "$tag: it does not claim to have added anything" test "$(grep -c 'added the key' <<<"$o")" -eq 0
}
check_bail "s4a(malformed)"  s4a '{"env": {"A": "b",,,'      'is not valid JSON'
check_bail "s4b(env=string)" s4b '{"env":"not-an-object"}'   'is string rather than an object'
check_bail "s4c(env=null)"   s4c '{"env":null}'              'is null rather than an object'
check_bail "s4d(top=array)"  s4d '[1,2,3]'                   'its top level is array, not an object'
ok "s4b: a valid-JSON shape problem is NOT reported as unparseable" \
  test "$(run_scaffold "$WORK/s4b" '{"source":"startup"}' | grep -c 'is not valid JSON')" -eq 0

# s5. idempotent: the second run changes nothing and says nothing
S5="$WORK/s5"; mk_fixture "$S5"
run_scaffold "$S5" '{"source":"startup"}' >/dev/null
cp "$(settings_of "$S5")" "$WORK/s5.before"
out="$(run_scaffold "$S5" '{"source":"startup"}')"
ok   "s5: second run leaves settings.json byte-identical" cmp -s "$(settings_of "$S5")" "$WORK/s5.before"
want "s5: second run is silent" "" "$out"

# s6. no jq -> verify nothing, write nothing, and SAY that presence is unverified
if ! no_jq_path_works; then
  echo "  SKIP  s6: could not build a PATH without jq"
else
  S6="$WORK/s6"; mk_fixture "$S6"
  printf '{"env":{"SOME_OTHER_VAR":"keep-me"}}\n' | seed_settings "$S6"
  cp "$(settings_of "$S6")" "$WORK/s6.before"
  out="$(PATH="$WORK/bin" run_scaffold "$S6" '{"source":"startup"}')"
  ok "s6(no-jq): the file is left byte-identical" cmp -s "$(settings_of "$S6")" "$WORK/s6.before"
  ok "s6(no-jq): it says it could neither verify nor edit" grep -q 'could neither verify nor safely edit' <<<"$out"
  ok "s6(no-jq): it names the key to add" grep -q "$KEY" <<<"$out"

  S6B="$WORK/s6b"; mk_fixture "$S6B"
  out="$(PATH="$WORK/bin" run_scaffold "$S6B" '{"source":"startup"}')"
  ok "s6b(no-jq): no settings.json is fabricated" test ! -e "$(settings_of "$S6B")"
  ok "s6b(no-jq): it still announces what to add" grep -q 'could neither verify nor safely edit' <<<"$out"

  # The substring trap: a file that merely MENTIONS the key inside an unrelated
  # string is not healed, and a grep-based presence check would have said it was.
  S6C="$WORK/s6c"; mk_fixture "$S6C"
  printf '{"env":{"NOTE":"see %s in the docs"}}\n' "$KEY" | seed_settings "$S6C"
  cp "$(settings_of "$S6C")" "$WORK/s6c.before"
